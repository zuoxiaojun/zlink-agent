def get_field_cn(table: str, field: str) -> str:
    info = ALL_TABLES.get(table.upper())
    if info:
        return info["fields"].get(field, field)
    return field


def translate_row(table: str, row: dict) -> dict:
    return {get_field_cn(table, k): v for k, v in row.items()}


def status_name(field: str, value: int) -> str | None:
    if field.upper() in ("FSTATUSFLAG", "FROWSTATUS"):
        return ORDER_STATUS.get(value)
    if field.upper() == "FORDERSTATUS":
        return PO_ORDER_STATUS.get(value)
    if field.upper() == "FPFSTATUSFLAG":
        return APPROVAL_STATUS.get(value)
    if field.upper() == "FONWAYSTATUS":
        return ONWAY_STATUS.get(value)
    return None
